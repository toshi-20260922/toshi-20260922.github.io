def files():
    return sorted(glob.glob(os.path.join(ROOT, 'site', '**', '*.html'), recursive=True)) + sorted(glob.glob(os.path.join(ROOT, 'tools', 'build*.py')))
def visible(s, f):
    if f.endswith('.py'):
        return s
    js = ' '.join(re.findall(r'"([^"]*[ぁ-ん][^"]*)"', ' '.join(re.findall(r'<script[^>]*>(.*?)</script>', s, re.S))))
    t = re.sub(r'<script.*?</script>|<style.*?</style>', '', s, flags=re.S)
    return re.sub(r'<[^>]+>', '', t) + '\n' + js
def find():
    out = []
    for f in files():
        v = visible(open(f, encoding='utf-8').read(), f)
        for p in NG:
            for m in re.finditer(p, v):
                out.append((os.path.relpath(f, ROOT), v[max(0, m.start() - 20):m.end() + 12].replace('\n', ' ')))
    return out
if __name__ == '__main__':
    if '--fix' in sys.argv:
        n = 0
        for f in files():
            s = open(f, encoding='utf-8').read(); o = s
            for a, b in FIX:
                s = s.replace(a, b)
            if s != o:
                open(f, 'w', encoding='utf-8').write(s); n += 1
        print('kotoba.py: 直したファイル', n)
    rest = find()
    for f, c in rest:
        print(f, '|', c)
    print('kotoba.py: 残り', len(rest))
