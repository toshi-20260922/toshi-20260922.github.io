def half(x):
    """本人負担の端数:50銭以下切り捨て・50銭超切り上げ。"""
    q = x.numerator // x.denominator
    return q + 1 if x - q > F(1, 2) else q

def hyojun(m):
    for s, top in TOKYU:
        if top is None or m < top:
            return s

def shaho(a, rate, old):
    """1年分の本人負担。(健康保険, 厚生年金, 雇用保険)。"""
    m = a // 12
    s = hyojun(m); p = min(max(s, 88000), 650000)
    r = rate + SIEN + (KAIGO if old else 0)
    return half(F(s * r, 20000)) * 12, half(F(p * NENKIN, 20000)) * 12, half(F(m * KOYO, 10000)) * 12

def kyuyo(x):
    """給与所得(令和8年分。住民税は令和9年度分で同じ)。No.1410 の表・注2・注3。"""
    if x < 741000: return 0
    if x < 2191000: return x - 740000
    if x < 2193000: return 1451000
    if x < 2196000: return 1453000
    if x < 2200000: return 1456000
    if x < 6600000:
        a = x // 4000 * 4000
        return a - (a * 3 // 10 + 80000) if x < 3600000 else a - (a * 2 // 10 + 440000)
    if x < 8500000: return x * 9 // 10 - 1100000          # 給与所得の1円未満は切り捨て
    return x - 1950000

def kiso_shotoku(g):
    for top, k in [(4890000, 1040000), (6550000, 670000), (23500000, 620000), (24000000, 480000), (24500000, 320000), (25000000, 160000)]:
        if g <= top: return k
    return 0

def kiso_jumin(g):
    for top, k in [(24000000, 430000), (24500000, 290000), (25000000, 150000)]:
        if g <= top: return k
    return 0

def ref(a, rate, old):
    k, nk, ko = shaho(a, rate, old); me = k + nk + ko
    g = kyuyo(a)
    t = max(0, g - me - kiso_shotoku(g)) // 1000 * 1000
    for top, r, d in SOKUSAN:
        if top is None or t <= top:
            base = t * r // 100 - d; break
    it = base * 1021 // 1000 // 100 * 100                  # 基準所得税額+復興特別所得税2.1%・100円未満切り捨て
    if g <= 450000:
        ju = 0                                             # 東京23区の単身:合計所得45万円以下は均等割も所得割もかからない
    else:
        tj = max(0, g - me - kiso_jumin(g)) // 1000 * 1000
        if g > 25000000: c6 = c4 = 0                       # 調整控除は合計所得2,500万円以下の人だけ
        else:
            adj = min(50000, tj) if tj <= 2000000 else 50000   # 200万円超は2,500円(=5万円×5%)
            c6, c4 = adj * 3 // 100, adj * 2 // 100
        ju = max(0, tj * 6 // 100 - c6) // 100 * 100 + max(0, tj * 4 // 100 - c4) // 100 * 100 + 5000
    return {'a': a, 'k': k, 'n': nk, 'e': ko, 's': me, 'i': it, 'j': ju, 't': a - me - it - ju, 'tax': t}

def r_half_up(fr): return (fr + F(1, 2)).__floor__()
def pct0(net, a): return r_half_up(F(net * 100, a)) if a else 0
def ritsu(net, a):
    v = r_half_up(F(net * 1000, a)); return '%d.%d' % (v // 10, v % 10)
def f(v): return '{:,}'.format(v)
def man(v): return r_half_up(F(v, 10000))

