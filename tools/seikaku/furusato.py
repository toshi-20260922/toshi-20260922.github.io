    for T in (0, 1950000, 3300000, 6950000, 9000000, 18000000, 40000000):   # 境目ちょうどの例が入っていること
        n += 1
        if not hit.get(T):
            bad += 1; print('NG 境目ちょうどの例が無い', T)
    rnd = random.Random(20261119)
    for _ in range(1500):
        a = rnd.choice([rnd.randrange(0, 3000000), rnd.randrange(0, 12000000), rnd.randrange(0, 50000001)])
        fam = (rnd.randrange(2), rnd.randrange(4), rnd.randrange(3))
