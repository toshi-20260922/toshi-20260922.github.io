def hyojun(m):
    s = 58
    for lo, v in GRADE:
        if m >= lo * 1000: s = v
    return s * 1000
def r50(v):                                       # 被保険者負担分:50銭以下切り捨て・50銭超切り上げ
    q = v.numerator // v.denominator
    return q + 1 if v - q > F(1, 2) else q
def shaho(a):
    m = a // 12
    s = hyojun(m)
    kenpo = r50(F(s) * (F(985, 10000) + F(23, 10000)) / 2)      # 健康保険9.85%+子ども・子育て支援金0.23%の半分
    nenkin = r50(F(min(max(s, 88000), 650000)) * F(183, 1000) / 2)
    koyo = r50(F(m) * F(5, 1000))
    return (kenpo + nenkin + koyo) * 12

# ---- 特例控除の割合を決める所得税率(地方税法37条の2第2項の表)。0円未満は0%(割合90%)、0円ちょうどは5%
BR = [(1950000, 5), (3300000, 10), (6950000, 20), (9000000, 23), (18000000, 33), (40000000, 40)]
def ritsu(x):
    if x < 0: return 0
    for top, r in BR:
        if x <= top: return r
    return 45

def ref(a, sp, n1, n2, sh=None):
    """上限額・所得割・式で使う所得税率。sh を渡さなければ協会けんぽ東京都の社会保険料。"""
    if sh is None: sh = shaho(a)
    g = kyuyo(a)
    if a > 8500000 and n1 + n2 > 0:               # 所得金額調整控除(1円未満切り上げ)
        g -= -(-(min(a, 10000000) - 8500000) // 10)
    nin = sp + n1 + n2
    if g <= 350000 * (nin + 1) + 100000 + (320000 if nin else 0):      # 所得割の非課税
        return {'lim': 0, 'sho': 0, 'rate': 0, 'x': None}
    kiso = 430000 if g <= 24000000 else 290000 if g <= 24500000 else 150000 if g <= 25000000 else 0
    hai = sa = 0
    if sp:
        hai, sa = (330000, 50000) if g <= 9000000 else (220000, 40000) if g <= 9500000 else (110000, 20000) if g <= 10000000 else (0, 0)
    tr = max(0, g - sh - kiso - hai - 330000 * n1 - 450000 * n2) // 1000 * 1000
    jsa = 50000 + sa + 50000 * n1 + 180000 * n2   # 人的控除差調整額
    if g > 25000000: cho = F(0)
    elif tr <= 2000000: cho = F(min(jsa, tr)) * 5 / 100
    else: cho = F(max(jsa - (tr - 2000000), 50000)) * 5 / 100
    sho = F(tr) / 10 - cho
    if sho <= 0:
        return {'lim': 0, 'sho': 0, 'rate': ritsu(tr - jsa), 'x': tr - jsa}
    r = ritsu(tr - jsa)
    lim = sho * F(20, 100) / (F(90, 100) - F(r) * F(1021, 1000) / 100) + 2000
    return {'lim': lim.numerator // lim.denominator, 'sho': sho.numerator // sho.denominator, 'rate': r, 'x': tr - jsa}

