KENPO, SIEN, NENKIN, KOYO = 985, 23, 1830, 5      # 健保・支援金・厚年は1万分の1、雇用は1000分の1

def half(x):
    """本人負担の端数:50銭以下切り捨て・50銭超切り上げ。"""
    q = x.numerator // x.denominator
    return q + 1 if x - q > F(1, 2) else q

def std(m):
    for top, s in GRADE:
        if top is None or m < top * 1000:
            return s * 1000

def si_month(m):
    h = std(m); p = min(max(h, 88000), 650000)
    return half(F(h * (KENPO + SIEN), 20000)) + half(F(p * NENKIN, 20000)) + half(F(m * KOYO, 1000))

def si_bonus(b):
    s = b // 1000 * 1000
    return (half(F(min(s, 5730000) * (KENPO + SIEN), 20000)) + half(F(min(s, 1500000) * NENKIN, 20000))
            + half(F(b * KOYO, 1000)))

def row(a, fu, y9):
    c = (R9 if y9 else R8)[min(fu, 7)]
    for j, top in enumerate(c):
        if a < top * 1000:
            return j
    return 20

def ref(m, b, fu, y9):
    k = si_month(m); a = m - k; i = row(a, fu, y9); s = si_bonus(b)
    z = (b - s) * RATE[i] // 100000                  # 1円未満切り捨て
    return {'sk': k, 'a': a, 'i': i, 'sb': s, 'zei': z, 'tedori': b - s - z, 'ten': (b - s) > a * 10}

def find_m(target):
    """前月の給与−社会保険料 がちょうど target になる前月の給与を探す(無ければ None)。"""
    for top, s in GRADE:
        m0 = target + si_month(s * 1000) - half(F(s * 1000 * KOYO, 1000))
        m0 = m0 * 1000 // 995
        for m in range(max(0, m0 - 4), m0 + 5):
            if std(m) == s * 1000 and m - si_month(m) == target:
                return m
    return None

def cell(c, j):
    f = lambda v: '{:,}'.format(v)
